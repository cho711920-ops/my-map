import {readFile,mkdir,writeFile,rename,rm} from 'node:fs/promises';
import {realpathSync} from 'node:fs';
import {createRequire} from 'node:module';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';

const ROOT=fileURLToPath(new URL('../',import.meta.url));
const require=createRequire(resolve(realpathSync(resolve(ROOT,'node_modules/wrangler')),'package.json'));
const {parse}=require('acorn');
const parseJs=source=>parse(source,{ecmaVersion:'latest',sourceType:'script'});
const source=async name=>readFile(resolve(ROOT,name),'utf8');

// Compile the existing display/filter functions ahead of time. The Worker
// never evaluates source strings and does not have a second set of price,
// source-selection, floor or sale-yield rules to drift from the browser.
export async function buildQueryRuntimeV151() {
  const script=await source('js/script.js'),map=await source('js/map.js');
  const functions=parseJs(script).body.filter(node=>node.type==='FunctionDeclaration');
  const declarations=functions.map(node=>script.slice(node.start,node.end)).join('\n');
  const mapFunctions=parseJs(map).body.filter(node=>node.type==='FunctionDeclaration' &&
    ['listingChangeRowToItemV683','parseDirectSaleDetailsV1'].includes(node.id.name)).map(node=>map.slice(node.start,node.end)).join('\n');
  const csvStart=map.indexOf('        var rawDeposit = clean(c[4]);'),csvEnd=map.indexOf('        item.key = itemKey(item);',csvStart);
  if(csvStart<0||csvEnd<csvStart)throw new Error('CSV master projection not found');
  const csvFunction='function csvMasterV151(c,i){\n'+map.slice(csvStart,csvEnd)+'\nitem.key=itemKey(item);return item;\n}';
  const installers=[];
  const inputs=[['Trade','js/listing-trade-ui-v1.js','JSListingTradeV1'],
    ['Parcel','js/parcel-external-links-v1.js','JSParcelExternalLinksV1'],
    ['Sale','js/sale-workbench-v1.js','JSSaleWorkbenchV1'],
    ['Brokerage','js/commercial-brokerage-v1.js','JSCommercialBrokerageV1'],
    ['Originals','js/unified-listings-v8.js','JSUnifiedListingsV8']];
  const hashes={};
  for (const [name,path,api] of inputs) {
    const text=await source(path);hashes[path]=createHash('sha256').update(text).digest('hex');
    const call=parseJs(text).body.find(n=>n.type==='ExpressionStatement' && n.expression.type==='CallExpression').expression;
    const statements=call.callee.body.body.filter(node=>node.type==='FunctionDeclaration' || node.type==='VariableDeclaration' ||
      node.type==='ExpressionStatement' && node.expression.type==='AssignmentExpression' &&
      node.expression.left.type==='MemberExpression' && node.expression.left.object.name==='global' && node.expression.left.property.name===api);
    if (!statements.some(n=>n.type==='ExpressionStatement')) throw new Error('Query API export not found: '+path);
    installers.push('function install'+name+'(global) {\n'+statements.map(n=>text.slice(n.start,n.end)).join('\n')+
      (name==='Trade'?'\nreturn mode=>{currentMode=mode;};':name==='Originals'?'\nreturn {expandUnifiedResult,thumbnailImagesV119,wholeBuildingKeyV55};':'')+'\n}');
  }
  const finalizeStart=script.indexOf('  // Sorting places complete building cards;'),finalizeEnd=script.indexOf('\n  return filtered;',finalizeStart);
  if(finalizeStart<0||finalizeEnd<finalizeStart)throw new Error('Query finalize projection not found');
  const finalizeFunction='function finalizeQueryV151(filtered,spec){const saleMode=spec.mode!=="lease",sortType=String(spec.filters?.sortFilter||"latest"),availabilityView=spec.availabilityView||(spec.doneOnly?"completed":spec.hideDone===false?"all":"active");\n'+
    script.slice(finalizeStart,finalizeEnd).replace('if (window.JSUnifiedListingsV8 &&','if (!spec.individualQueryV152 && window.JSUnifiedListingsV8 &&')+'\nreturn filtered;\n}';
  const capturedDeclarations=declarations.replace('    return matchTradeMode &&', '    var matchedProjectionV177 = matchTradeMode &&').replace('matchFavorite && matchDone && matchGongsil && matchTodayNew && inMap;', 'matchFavorite && matchDone && matchGongsil && matchTodayNew && inMap;\n    if(matchedProjectionV177 && options && options.captureProjectionV177)options.captureProjectionV177(item);\n    return matchedProjectionV177;');
  const batchDeclarations=capturedDeclarations.replace('  // Sorting places complete building cards;','  if(options && options.deferQueryFinalizeV151)return filtered;\n  // Sorting places complete building cards;');
  const adapter=await source('cloudflare/src/query-runtime-adapter-v151.inc');
  const content='// Generated by tools/build-query-runtime-v151.mjs; do not edit.\n'+
    '// Source digests: '+JSON.stringify({...hashes,'js/script.js':createHash('sha256').update(script).digest('hex'),'js/map.js':createHash('sha256').update(map).digest('hex')})+'\n'+
    adapter.replace('/* QUERY_DECLARATIONS_V151 */',batchDeclarations+'\n'+mapFunctions+'\n'+csvFunction+'\n'+finalizeFunction+'\n'+installers.join('\n')+
      '\nObject.assign(window,{'+functions.map(node=>node.id.name).join(',')+'});');
  await mkdir(resolve(ROOT,'cloudflare/generated'),{recursive:true});
  const output=resolve(ROOT,'cloudflare/generated/query-runtime-v151.js');
  if(await readFile(output,'utf8').catch(()=>null)!==content){
    const temporary=output+'.'+process.pid+'.'+Math.random().toString(36).slice(2)+'.tmp';
    try {await writeFile(temporary,content);await rename(temporary,output);}finally{await rm(temporary,{force:true});}
  }
  return {bytes:Buffer.byteLength(content),sources:Object.keys(hashes).length+2};
}

if (process.argv[1] && resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(await buildQueryRuntimeV151()));
}
